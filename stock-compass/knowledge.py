def api_knowledge(params):
    q = str((params or {}).get("q") or "").strip()
    if not q:
        return doc()
    hits = search(q)
    return {"ok": True, "q": q, "hits": hits, "count": len(hits),
            "version": VERSION,
            "disclaimer": DISCLAIMER}


