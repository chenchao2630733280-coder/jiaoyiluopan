def _expand(q):
    """把查询词扩展成一组关键词（原词 + 同义词 + 中文二元组）"""
    kws = {q}
    for k, vs in SYNONYMS.items():
        if k in q:
            kws.add(k)
            kws.update(vs)
    # 中文按二元组切，让「怎么设止损」也能匹配到「止损」
    for i in range(len(q) - 1):
        bg = q[i:i + 2]
        if re.match(r"^[\u4e00-\u9fa5]{2}$", bg):
            kws.add(bg)
    return [k for k in kws if k]


def _hit_score(kws, weighted):
    """weighted = [(文本, 权重), ...]；返回总分"""
    total = 0
    for text, w in weighted:
        if not text:
            continue
        t = str(text)
        for k in kws:
            if k and k in t:
                total += w * (2 if len(k) >= 2 else 1)
    return total


def search(q, limit=40):
    kws = _expand(q or "")
    scored = []

    for f in FAQ:
        s = _hit_score(kws, [(f["q"], 6), (" ".join(f.get("tags") or []), 4), (f["a"], 2)])
        if s > 0:
            scored.append((s, {"type": "faq", "q": f["q"], "a": f["a"], "tags": f.get("tags") or []}))

    for b in BOOKS:
        s = _hit_score(kws, [(b["title"], 6), (b["focus"], 5), (b["tagline"], 3),
                             (b["points"], 3), (b["note"], 2), (b["author"], 3)])
        if s > 0:
            scored.append((s, {"type": "book", "title": b["title"], "author": b["author"],
                               "points": b["points"], "note": b["note"], "focus": b["focus"]}))

    for sec in SECTIONS:
        for it in sec["items"]:
            s = _hit_score(kws, [(it["k"], 5), (it["v"], 3), (sec["title"], 2)])
            if s > 0:
                scored.append((s, {"type": "item", "icon": sec["icon"], "k": it["k"], "v": it["v"],
                                   "section": sec["title"], "book": sec["book"]}))

    scored.sort(key=lambda x: -x[0])
    return [x[1] for x in scored[:limit]]


