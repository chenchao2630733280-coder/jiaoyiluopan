def build(include_missing=False):
    """把 curated 的 code 列表贴到当前快照上：补名称与 secid，剔除已退市/停牌的。

    ★ 名称与 secid 一律运行时取，不在本文件写死 —— 改过一次名（银泰黄金→山金国际）
      就会让页面显示旧名，这种错没人会去核对。
    """
    snap = engine.snap_index()
    out, missing = [], []
    for ind in INDUSTRIES:
        stocks = []
        for code in ind["codes"]:
            row = snap.get(code)
            if not row or not row.get("price"):
                missing.append(code)
                continue
            # ST/*ST 不进产业代表名单：政策叙事页挂退市风险股会误导
            if engine.is_st(row.get("name") or ""):
                missing.append("%s(ST)" % code)
                continue
            stocks.append({
                "code": code,
                "name": row.get("name") or code,
                "secid": engine.secid_of_code(code),
                "price": row.get("price"),
                "pct": row.get("pct"),
                "board": row.get("board"),
            })
            if len(stocks) >= MAX_STOCKS:
                break
        if not stocks:
            missing.append("%s(整组)" % ind["name"])
            continue
        out.append({
            "name": ind["name"], "tier": ind["tier"], "stars": ind["stars"],
            "sectors": ind["sectors"], "logic": ind["logic"], "stocks": stocks,
        })

    order = {"pillar": 0, "future": 1, "strategic": 2}
    out.sort(key=lambda x: (order.get(x["tier"], 9), -x["stars"]))

    res = {
        "ok": True, "empty": not out,
        "source": SOURCE,
        "updated": time.strftime("%Y-%m-%d %H:%M:%S"),
        "tiers": TIERS,
        "list": out,
        "count": len(out),
        "stock_count": sum(len(x["stocks"]) for x in out),
        "note": "产业归属为本系统按政策口径与主营业务的人工映射，一只股票可同时属多个产业；"
                "本页只回答「这个方向上有哪些票」，不做买卖判断，个股结论请走十二维体检。",
        "disclaimer": "政策口径引自公开文件与发布会，映射关系与公司主营判断为人工整理，可能存在错配，不构成投资建议。",
    }
    if include_missing:
        res["missing"] = missing
    return res


